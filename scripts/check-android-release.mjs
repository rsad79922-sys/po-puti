import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {readFileSync} from 'node:fs';
const apk=process.argv[2],expectedPackage=process.env.ANDROID_EXPECTED_PACKAGE||'ru.poputi.app';
const fingerprint=String(process.env.ANDROID_PREVIOUS_CERT_SHA256||'').replace(/:/g,'').toLowerCase();
const oldCode=Number(process.env.ANDROID_PREVIOUS_VERSION_CODE);
if(!apk||!Number.isInteger(oldCode)||oldCode<1||!/^[a-f0-9]{64}$/.test(fingerprint))throw Error('APK, previous published versionCode and public certificate SHA-256 are required; signing keys are not accepted by this checker');
const badging=execFileSync(process.env.AAPT||'aapt',['dump','badging',apk],{encoding:'utf8'});
const pkg=badging.match(/package: name='([^']+)' versionCode='(\d+)'/);
if(!pkg||pkg[1]!==expectedPackage||Number(pkg[2])<=oldCode)throw Error('Package changed or versionCode does not exceed the existing publication');
if(badging.includes('application-debuggable'))throw Error('Debuggable APK cannot be released');
const cert=execFileSync(process.env.APKSIGNER||'apksigner',['verify','--verbose','--print-certs',apk],{encoding:'utf8'});
const actual=cert.match(/Signer #1 certificate SHA-256 digest: ([a-f0-9:]+)/i)?.[1].replace(/:/g,'').toLowerCase();
if(actual!==fingerprint)throw Error('Release signer does not match the existing publication; do not uninstall the app or replace the card');
console.log(JSON.stringify({ok:true,package:pkg[1],versionCode:Number(pkg[2]),certificateSHA256:actual,apkSHA256:createHash('sha256').update(readFileSync(apk)).digest('hex')}));
